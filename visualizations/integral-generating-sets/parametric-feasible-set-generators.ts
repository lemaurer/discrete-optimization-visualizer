const cone2DViewport = { x: [-0.5, 8.8] as [number, number], y: [-0.5, 9.2] as [number, number] };
const cone2DPolygon: Point2D[] = [[0, 0], [8.5, 0], [8.5, 9], [5.4, 9]];

function cone2DLattice(): Primitive[] {
  const result: Primitive[] = [];
  for (let x = 0; x <= 8; x += 1) {
    for (let y = 0; y <= 9; y += 1) {
      if (5 * x >= 3 * y) result.push(point2D([x, y], undefined, "lattice"));
    }
  }
  return result;
}

function layerLines2D(maxLayer = 5): Primitive[] {
  const result: Primitive[] = [];
  for (let j = 1; j <= maxLayer; j += 1) {
    result.push(line2D([0, j], [8.5, j], `y=${j}`, C.muted, "assignment"));
  }
  return result;
}

function sceneFor2D(extra: Primitive[], secondary: string) {
  return scene2D(
    [
      polygon2D(cone2DPolygon, "C=cone((1,0),(3,5))", "feasible"),
      ...cone2DLattice(),
      line2D([0, 0], [8.5, 0], "e₁=(1,0)", C.orange, "constraint"),
      line2D([0, 0], [5.4, 9], "p=(3,5)", C.aqua, "constraint"),
      ...extra,
    ],
    {
      primary: "Parametric integral generating set · p=(3,5)",
      secondary,
    },
    { viewport: cone2DViewport },
  );
}

