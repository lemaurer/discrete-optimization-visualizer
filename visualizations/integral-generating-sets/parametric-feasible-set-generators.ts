// Natural 3D analogue: C=cone(e1,e2,p), p=(2,3,5).
// This extension is not stated separately in the notes, but the same proof works coordinatewise.
const E1: Point3D = [1, 0, 0];
const E2: Point3D = [0, 1, 0];
const P3: Point3D = [2, 3, 5];
const H3: Point3D[] = [[1, 1, 1], [1, 2, 2], [2, 2, 3], [2, 3, 4], [2, 3, 5]];

function scale3(t: number, v: Point3D): Point3D {
  return [t * v[0], t * v[1], t * v[2]];
}

function coneMesh3D(scale: number): Mesh3D {
  return {
    id: `param-cone-${scale}`,
    vertices: [[0, 0, 0], scale3(scale, E1), scale3(scale, E2), scale3(scale, P3)],
    faces: [[0, 1, 2], [0, 1, 3], [0, 2, 3], [1, 2, 3]],
    label: "truncated cone C",
    color: C.lime,
    edgeColor: C.muted,
    opacity: 0.17,
    style: "ghost",
  };
}

function coneCoordinates3D(q: Point3D): [number, number, number] {
  const l3 = q[2] / 5;
  return [q[0] - 2 * l3, q[1] - 3 * l3, l3];
}

function lattice3D(scale: number): Marker3D[] {
  const result: Marker3D[] = [];
  for (let x = 0; x <= 6; x += 1) {
    for (let y = 0; y <= 8; y += 1) {
      for (let z = 0; z <= 10; z += 1) {
        const q: Point3D = [x, y, z];
        const [l1, l2, l3] = coneCoordinates3D(q);
        if (l1 < -1e-9 || l2 < -1e-9 || l3 < -1e-9 || l1 + l2 + l3 > scale + 1e-9) continue;
        result.push(marker3D(`param-lattice-${x}-${y}-${z}`, q, undefined, "integer", 0.038));
      }
    }
  }
  return result;
}

const bounds3D: Scene3D["bounds"] = { x: [-0.4, 6.2], y: [-0.4, 8.2], z: [-0.4, 10.6] };

function base3D(
  extraMarkers: Marker3D[] = [],
  extraSegments: Segment3D[] = [],
  caption: { primary: string; secondary: string } = {
    primary: "Natural 3D analogue",
    secondary: "C=cone(e₁,e₂,(2,3,5)).",
  },
) {
  return scene3D({
    bounds: bounds3D,
    axisLabels: { x: "x₁", y: "x₂", z: "x₃" },
    camera: { yaw: 0.82, pitch: 0.48, distance: 12.0 },
    verticalScale: 0.62,
    meshes: [coneMesh3D(2)],
    markers: [...lattice3D(2), ...extraMarkers],
    segments: [
      segment3D("param-e1", [0, 0, 0], scale3(3.5, E1), "e₁", C.orange),
      segment3D("param-e2", [0, 0, 0], scale3(3.5, E2), "e₂", C.aqua),
      segment3D("param-p", [0, 0, 0], P3, "p=(2,3,5)", C.violet),
      ...extraSegments,
    ],
    showAxes: true,
    showGround: true,
    showIntegerLattice: false,
    caption,
  });
}

