const conePolygon2D: Point2D[] = [[0, 0], [8.5, 0], [8.5, 9], [5.4, 9]];

function lattice2D(): Primitive[] {
  const result: Primitive[] = [];
  for (let x = 0; x <= 8; x += 1) {
    for (let y = 0; y <= 9; y += 1) {
      if (5 * x >= 3 * y) result.push(point2D([x, y], undefined, "lattice"));
    }
  }
  return result;
}

function base2D(extra: Primitive[], secondary: string) {
  return scene2D(
    [
      polygon2D(conePolygon2D, "C=cone((1,0),(3,5))", "feasible"),
      ...lattice2D(),
      line2D([0, 0], [8.5, 0], "e₁=(1,0)", C.orange, "constraint"),
      line2D([0, 0], [5.4, 9], "p=(3,5)", C.aqua, "constraint"),
      ...extra,
    ],
    {
      primary: "Parametric integral generating set · p=(3,5)",
      secondary,
    },
    { viewport: { x: [-0.5, 8.8], y: [-0.5, 9.2] } },
  );
}

