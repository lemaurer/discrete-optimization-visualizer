// -----------------------------------------------------------------------------
// Natural 3D analogue (not stated separately in the notes):
// C=cone(e1,e2,p), p=(2,3,5).
// The same residue argument gives
// H={e1,e2}∪{(ceil(2j/5),ceil(3j/5),j): j=1,...,5}.
// -----------------------------------------------------------------------------

const e1: Point3D = [1, 0, 0];
const e2: Point3D = [0, 1, 0];
const p3: Point3D = [2, 3, 5];
const h3D: Point3D[] = [
  [1, 1, 1],
  [1, 2, 2],
  [2, 2, 3],
  [2, 3, 4],
  [2, 3, 5],
];

function scale3(lambda: number, v: Point3D): Point3D {
  return [lambda * v[0], lambda * v[1], lambda * v[2]];
}

function truncatedCone3D(scale: number, id: string): Mesh3D {
  return {
    id,
    vertices: [[0, 0, 0], scale3(scale, e1), scale3(scale, e2), scale3(scale, p3)],
    faces: [[0, 1, 2], [0, 1, 3], [0, 2, 3], [1, 2, 3]],
    label: "truncated C=cone(e₁,e₂,p)",
    color: C.lime,
    edgeColor: C.muted,
    opacity: 0.17,
    style: "ghost",
  };
}

function coneCoordinates3D(q: Point3D): [number, number, number] {
  const lambda3 = q[2] / 5;
  return [q[0] - 2 * lambda3, q[1] - 3 * lambda3, lambda3];
}

function coneLattice3D(scale: number): Marker3D[] {
  const result: Marker3D[] = [];
  const xMax = Math.ceil(2 * scale + scale);
  const yMax = Math.ceil(3 * scale + scale);
  const zMax = Math.ceil(5 * scale);
  for (let x = 0; x <= xMax; x += 1) {
    for (let y = 0; y <= yMax; y += 1) {
      for (let z = 0; z <= zMax; z += 1) {
        const q: Point3D = [x, y, z];
        const [l1, l2, l3] = coneCoordinates3D(q);
        if (l1 < -1e-9 || l2 < -1e-9 || l3 < -1e-9) continue;
        if (l1 + l2 + l3 > scale + 1e-9) continue;
        result.push(marker3D(`param3-lattice-${x}-${y}-${z}`, q, undefined, "integer", 0.038));
      }
    }
  }
  return result;
}

const bounds3D: Scene3D["bounds"] = { x: [-0.4, 6.2], y: [-0.4, 7.3], z: [-0.4, 10.6] };

function base3D(extraMarkers: Marker3D[] = [], extraSegments = [], caption?: { primary: string; secondary: string }) {
  return scene3D({
    bounds: bounds3D,
    axisLabels: { x: "x₁", y: "x₂", z: "x₃" },
    camera: { yaw: 0.82, pitch: 0.48, distance: 12.2 },
    verticalScale: 0.62,
    meshes: [truncatedCone3D(2, "param3-cone")],
    markers: [...coneLattice3D(2), ...extraMarkers],
    segments: [
      segment3D("param3-e1", [0, 0, 0], scale3(3.5, e1), "e₁", C.orange),
      segment3D("param3-e2", [0, 0, 0], scale3(3.5, e2), "e₂", C.aqua),
      segment3D("param3-p", [0, 0, 0], p3, "p=(2,3,5)", C.violet),
      ...extraSegments,
    ],
    showAxes: true,
    showGround: true,
    showIntegerLattice: false,
    caption: caption ?? {
      primary: "Natural 3D analogue",
      secondary: "The cone is generated by two coordinate rays and p=(2,3,5).",
    },
  });
}

