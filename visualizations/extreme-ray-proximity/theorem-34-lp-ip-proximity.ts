function scene3D(configuration: Scene3D): Scene {
  return {
    viewport: { x: [0, 1], y: [0, 1] },
    constraints: [],
    showGrid: true,
    showLattice: true,
    showVertices: true,
    scene3D: configuration,
  };
}

function basePolyhedron(opacity = 0.18): Mesh3D {
  return boxMesh("proximity-box", [0, 4], [0, 4], [0, 2], {
    label: "P",
    color: "#79c9c0",
    opacity,
  });
}

