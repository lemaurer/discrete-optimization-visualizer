function boxVertices(
  x: [number, number],
  y: [number, number],
  z: [number, number],
): Point3D[] {
  return [
    [x[0], y[0], z[0]],
    [x[1], y[0], z[0]],
    [x[1], y[1], z[0]],
    [x[0], y[1], z[0]],
    [x[0], y[0], z[1]],
    [x[1], y[0], z[1]],
    [x[1], y[1], z[1]],
    [x[0], y[1], z[1]],
  ];
}

function boxMesh(
  id: string,
  x: [number, number],
  y: [number, number],
  z: [number, number],
  options: Partial<Mesh3D> = {},
): Mesh3D {
  return {
    id,
    vertices: boxVertices(x, y, z),
    faces: boxFaces,
    style: "solid",
    ...options,
  };
}

