import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const visualizationsRoot = path.join(repositoryRoot, "visualizations");
const outputPath = path.join(visualizationsRoot, "generated.ts");
const ignoredFiles = new Set(["generated.ts", "registry.ts", "types.ts"]);
const ignoredDirectories = new Set(["helpers"]);

async function collectTypeScriptFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const absolutePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (ignoredDirectories.has(entry.name)) return [];
        return collectTypeScriptFiles(absolutePath);
      }
      if (!entry.isFile() || !entry.name.endsWith(".ts") || ignoredFiles.has(entry.name)) {
        return [];
      }
      return [absolutePath];
    }),
  );
  return files.flat();
}

const moduleFiles = (await collectTypeScriptFiles(visualizationsRoot)).sort();

if (moduleFiles.length === 0) {
  throw new Error("No visualization modules were found under visualizations/.");
}

const importLines = moduleFiles.map((absolutePath, index) => {
  const relativePath = path
    .relative(visualizationsRoot, absolutePath)
    .split(path.sep)
    .join("/")
    .replace(/\.ts$/, "");
  return `import visualization${index} from "./${relativePath}";`;
});

const registrySource = `// This file is generated by scripts/generate-visualization-registry.mjs.
// Add visualization modules under visualizations/<chapter>/ and run npm run dev or npm run build.

${importLines.join("\n")}

export const generatedVisualizations = [
${moduleFiles.map((_, index) => `  visualization${index},`).join("\n")}
];
`;

await writeFile(outputPath, registrySource, "utf8");
console.log(`Discovered ${moduleFiles.length} visualization module${moduleFiles.length === 1 ? "" : "s"}.`);
